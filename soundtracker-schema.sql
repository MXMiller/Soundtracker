-- Soundtracker schema for PostgreSQL on Supabase.
-- Run in a Supabase project after Auth is enabled. Each profile id is the
-- corresponding auth.users id; authentication credentials stay in Supabase Auth.
-- Store uploaded media in Supabase Storage and keep its object path here.

CREATE TYPE soundtrack_visibility AS ENUM ('open', 'public', 'private');
CREATE TYPE soundtrack_permission AS ENUM ('view', 'edit');
CREATE TYPE story_item_type AS ENUM ('character', 'setting', 'idea', 'other');

CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    profile_image_file_path TEXT,
    avatar_color TEXT,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.soundtracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    listening_url TEXT,
    visibility soundtrack_visibility NOT NULL DEFAULT 'private',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX soundtracks_owner_idx ON public.soundtracks(owner_id);
CREATE INDEX soundtracks_visibility_updated_idx ON public.soundtracks(visibility, updated_at DESC);
CREATE INDEX soundtracks_name_idx ON public.soundtracks(name);

CREATE TABLE public.soundtrack_composers (
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    composer_name VARCHAR(255) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    PRIMARY KEY (soundtrack_id, composer_name)
);

-- Open soundtracks are editable by any authenticated user; public soundtracks
-- are view-only. Private soundtrack access is granted explicitly here.
CREATE TABLE public.soundtrack_access (
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    permission soundtrack_permission NOT NULL DEFAULT 'view',
    granted_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (soundtrack_id, user_id)
);
CREATE INDEX soundtrack_access_user_idx ON public.soundtrack_access(user_id);

CREATE TABLE public.soundtrack_favorites (
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, soundtrack_id)
);
CREATE INDEX soundtrack_favorites_soundtrack_idx ON public.soundtrack_favorites(soundtrack_id);

CREATE TABLE public.story_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    item_type story_item_type NOT NULL DEFAULT 'other',
    description TEXT,
    image_file_path TEXT,
    key_signature VARCHAR(64),
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, soundtrack_id)
);
CREATE INDEX story_items_soundtrack_order_idx ON public.story_items(soundtrack_id, sort_order);

CREATE TABLE public.instruments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE
);

CREATE TABLE public.story_item_instruments (
    story_item_id BIGINT NOT NULL REFERENCES public.story_items(id) ON DELETE CASCADE,
    instrument_id BIGINT NOT NULL REFERENCES public.instruments(id) ON DELETE RESTRICT,
    PRIMARY KEY (story_item_id, instrument_id)
);

CREATE TABLE public.leitmotifs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    notation_file_path TEXT,
    notation_url TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, soundtrack_id)
);
CREATE INDEX leitmotifs_soundtrack_order_idx ON public.leitmotifs(soundtrack_id, sort_order);

CREATE TABLE public.story_item_leitmotifs (
    story_item_id BIGINT NOT NULL,
    leitmotif_id BIGINT NOT NULL,
    soundtrack_id BIGINT NOT NULL,
    PRIMARY KEY (story_item_id, leitmotif_id),
    FOREIGN KEY (story_item_id, soundtrack_id)
        REFERENCES public.story_items(id, soundtrack_id) ON DELETE CASCADE,
    FOREIGN KEY (leitmotif_id, soundtrack_id)
        REFERENCES public.leitmotifs(id, soundtrack_id) ON DELETE CASCADE
);
CREATE INDEX story_item_leitmotifs_motif_idx ON public.story_item_leitmotifs(leitmotif_id);

CREATE TABLE public.leitmotif_derivations (
    parent_leitmotif_id BIGINT NOT NULL,
    derived_leitmotif_id BIGINT NOT NULL,
    soundtrack_id BIGINT NOT NULL,
    PRIMARY KEY (parent_leitmotif_id, derived_leitmotif_id),
    FOREIGN KEY (parent_leitmotif_id, soundtrack_id)
        REFERENCES public.leitmotifs(id, soundtrack_id) ON DELETE CASCADE,
    FOREIGN KEY (derived_leitmotif_id, soundtrack_id)
        REFERENCES public.leitmotifs(id, soundtrack_id) ON DELETE CASCADE,
    CHECK (parent_leitmotif_id <> derived_leitmotif_id)
);

CREATE TABLE public.tracks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soundtrack_id BIGINT NOT NULL REFERENCES public.soundtracks(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    track_number INTEGER CHECK (track_number IS NULL OR track_number > 0),
    listening_url TEXT,
    audio_file_path TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, soundtrack_id),
    UNIQUE (soundtrack_id, track_number)
);
CREATE INDEX tracks_soundtrack_order_idx ON public.tracks(soundtrack_id, sort_order);

CREATE TABLE public.track_composers (
    track_id BIGINT NOT NULL REFERENCES public.tracks(id) ON DELETE CASCADE,
    composer_name VARCHAR(255) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    PRIMARY KEY (track_id, composer_name)
);

CREATE TABLE public.track_leitmotifs (
    track_id BIGINT NOT NULL,
    leitmotif_id BIGINT NOT NULL,
    soundtrack_id BIGINT NOT NULL,
    appearance_in_track VARCHAR(255),
    appearance_in_story VARCHAR(255),
    description TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    PRIMARY KEY (track_id, leitmotif_id),
    FOREIGN KEY (track_id, soundtrack_id)
        REFERENCES public.tracks(id, soundtrack_id) ON DELETE CASCADE,
    FOREIGN KEY (leitmotif_id, soundtrack_id)
        REFERENCES public.leitmotifs(id, soundtrack_id) ON DELETE CASCADE
);
CREATE INDEX track_leitmotifs_motif_idx ON public.track_leitmotifs(leitmotif_id);

-- Keep modification timestamps current for edits made through the API or SQL.
CREATE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER profiles_set_updated_at
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER soundtracks_set_updated_at
    BEFORE UPDATE ON public.soundtracks
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER story_items_set_updated_at
    BEFORE UPDATE ON public.story_items
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER leitmotifs_set_updated_at
    BEFORE UPDATE ON public.leitmotifs
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER tracks_set_updated_at
    BEFORE UPDATE ON public.tracks
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
